#!/usr/bin/env node
// Skill library for workers: index every installed skill, let the orchestrator pick them,
// and hand workers exact, existing skill files (never a name they have to guess).
//
//   node .agent-hub/tools/skills.mjs build                 rescan skillRoots, write skills/INDEX.md + index.json
//   node .agent-hub/tools/skills.mjs find <words...>       best matches by name and description
//   node .agent-hub/tools/skills.mjs show <name>           path + full description of one skill
//   node .agent-hub/tools/skills.mjs check <TASK>          validate the brief's ## Skills section
//   node .agent-hub/tools/skills.mjs stage <TASK>          check + copy the skills into skills-cache/ (dispatch calls this)
//
// Brief format (the only one accepted):
//   ## Skills
//   - `skill-name`: why this task needs it
// Write "- none" when no skill applies. A name not in the index fails check, so dispatch refuses the task.
import { fileURLToPath } from 'node:url';
import { help, auditPath, CFG as CONFIG, hubDir, projectPath } from './runtime.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const HUB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = path.dirname(HUB);
const DIR = path.join(HUB, 'skills');
const CACHE = path.join(HUB, 'skills-cache');
const INDEX_JSON = path.join(DIR, 'index.json');
const CFG = (() => { try { return JSON.parse(fs.readFileSync(path.join(HUB, 'config.json'), 'utf8')); } catch { return {}; } })();
const expand = (p) => path.resolve(ROOT, p.replace(/^~(?=[\\/]|$)/, os.homedir()));
// First root wins on a name clash, so project skills override the personal library.
const ROOTS = (CFG.skillRoots ?? ['.claude/skills', '~/.claude/skills', '~/.agents/skills', '~/.codex/skills', '~/.gemini/skills']).map(expand);
const MAX_COPY_BYTES = 3 * 1024 * 1024;
// Skills above this size are skimmed (head + grep) instead of read fully, to protect the worker's context.
const SKIM_KB = 12;
const SKIM_LINES = 120;
const SKIP_DIRS = new Set(['node_modules', '.git', '__pycache__', 'dist', 'build', '.venv']);

function frontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const out = {};
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (!kv) continue;
    let [, k, v] = kv;
    if (/^[|>][-+]?$/.test(v.trim())) {
      // Block scalar: take the indented lines that follow.
      const buf = [];
      while (i + 1 < lines.length && (/^\s+\S/.test(lines[i + 1]) || lines[i + 1].trim() === '')) buf.push(lines[++i].trim());
      v = buf.join(' ');
    }
    out[k] = v.trim().replace(/^["']|["']$/g, '').replace(/\s+/g, ' ');
  }
  return out;
}

function findSkillFiles(dir, depth = 0, acc = []) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return acc; }
  if (entries.some((e) => e.name === 'SKILL.md') && depth > 0) acc.push(path.join(dir, 'SKILL.md'));
  if (depth >= 3) return acc;
  for (const e of entries) {
    if (SKIP_DIRS.has(e.name) || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    let isDir = e.isDirectory();
    if (e.isSymbolicLink()) { try { isDir = fs.statSync(p).isDirectory(); } catch { isDir = false; } }
    if (isDir) findSkillFiles(p, depth + 1, acc);
  }
  return acc;
}

function build() {
  const byName = new Map();
  const seenReal = new Set();
  let scanned = 0;
  for (const root of ROOTS) {
    for (const file of findSkillFiles(root)) {
      scanned++;
      let real;
      try { real = fs.realpathSync(file); } catch { continue; }
      if (seenReal.has(real)) continue;
      seenReal.add(real);
      const fm = frontmatter(fs.readFileSync(real, 'utf8'));
      // Display names ("Refactor Safely") fall back to the folder name so briefs always use plain ids.
      const fmName = (fm.name ?? '').trim();
      const name = /^[a-z0-9][a-z0-9:._-]*$/.test(fmName) ? fmName : path.basename(path.dirname(file)).toLowerCase();
      if (byName.has(name)) continue;
      byName.set(name, { name, description: fm.description ?? '', file: real.replace(/\\/g, '/'), root: root.replace(/\\/g, '/') });
    }
  }
  const skills = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
  fs.mkdirSync(DIR, { recursive: true });
  fs.writeFileSync(INDEX_JSON, JSON.stringify({ built: new Date().toISOString(), roots: ROOTS, skills }, null, 1));
  const md = [
    '# Skill library index',
    '',
    `Generated by \`node .agent-hub/tools/skills.mjs build\` on ${new Date().toISOString().slice(0, 10)}. ${skills.length} skills. Do not edit by hand; rebuild after installing skills.`,
    '',
    'Orchestrator: pick skills with `skills.mjs find <words>`, list them in the brief under `## Skills` as `` - `name`: why ``, and run `skills.mjs check <TASK>`. Workers never browse this file; they read only the skills their brief stages for them.',
    '',
    ...skills.map((s) => `- \`${s.name}\`: ${s.description.slice(0, 180)}${s.description.length > 180 ? '...' : ''}`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(DIR, 'INDEX.md'), md);
  const starter = path.join(DIR, 'STARTER.md');
  if (!fs.existsSync(starter)) fs.writeFileSync(starter, '# Skill starter\n\nUse skills.mjs find <words>, then check <TASK>. Project roots take precedence. List exact names with a reason under ## Skills, or - none.\n');
  console.log(`indexed ${skills.length} skills (${scanned} SKILL.md files scanned across ${ROOTS.length} roots) -> ${path.relative(ROOT, DIR)}/INDEX.md`);
}

function load() {
  if (!fs.existsSync(INDEX_JSON)) build();
  return JSON.parse(fs.readFileSync(INDEX_JSON, 'utf8')).skills;
}

function find(words) {
  const terms = words.join(' ').toLowerCase().split(/\s+/).filter(Boolean);
  const scored = load().map((s) => {
    const n = s.name.toLowerCase(), d = s.description.toLowerCase();
    const score = terms.reduce((t, w) => t + (n === w ? 10 : n.includes(w) ? 4 : 0) + (d.includes(w) ? 1 : 0), 0);
    return { s, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score || a.s.name.localeCompare(b.s.name)).slice(0, 15);
  if (!scored.length) return console.log('no match');
  for (const { s, score } of scored) console.log(`${String(score).padStart(3)}  ${s.name.padEnd(36)} ${s.description.slice(0, 110)}`);
}

// Returns [{name, why, skill}] or throws with every problem listed.
export function briefSkills(taskId) {
  const brief = path.join(HUB, 'tasks', `${taskId}.md`);
  if (!fs.existsSync(brief)) throw new Error(`no brief: ${path.relative(ROOT, brief)}`);
  const text = fs.readFileSync(brief, 'utf8');
  const sec = text.match(/^## Skills\s*\r?\n([\s\S]*?)(?=^## |(?![\s\S]))/m);
  if (!sec && !CFG.requireSkills) return [];
  if (!sec) throw new Error(`${taskId}: brief has no "## Skills" section (write "- none" if no skill applies)`);
  const lines = sec[1].split(/\r?\n/).map((l) => l.trim()).filter((l) => l.startsWith('-'));
  if (lines.length === 1 && /^-\s*none\b/i.test(lines[0])) return [];
  const index = new Map(load().map((s) => [s.name, s]));
  const out = [], bad = [];
  for (const l of lines) {
    const m = l.match(/^-\s*`([^`]+)`\s*:?\s*(.*)$/);
    if (!m) { bad.push(`bad line (use - \`name\`: why): ${l}`); continue; }
    const skill = index.get(m[1]);
    if (!skill) { bad.push(`unknown skill "${m[1]}" (try: skills.mjs find ${m[1].split(/[-_]/)[0]})`); continue; }
    if (!fs.existsSync(skill.file)) { bad.push(`skill "${m[1]}" file is gone: ${skill.file} (run skills.mjs build)`); continue; }
    if (!m[2]) { bad.push(`skill "${m[1]}" has no reason; say why this task needs it`); continue; }
    out.push({ name: m[1], why: m[2], skill });
  }
  if (!lines.length) bad.push('## Skills section is empty (write "- none" if no skill applies)');
  if (bad.length) throw new Error(`${taskId} skills:\n  ${bad.join('\n  ')}`);
  return out;
}

function copyDir(src, dest, budget) {
  fs.mkdirSync(dest, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (SKIP_DIRS.has(e.name) || e.isSymbolicLink()) continue;
    const s = path.join(src, e.name), d = path.join(dest, e.name);
    const st = fs.statSync(s);
    if (st.isDirectory()) { copyDir(s, d, budget); continue; }
    if (budget.left - st.size < 0) { budget.skipped.push(e.name); continue; }
    budget.left -= st.size;
    fs.copyFileSync(s, d);
  }
}

// Copies each listed skill folder into skills-cache/<name>/ so every executor can read it inside the repo,
// even CLIs that refuse paths outside the working tree. Returns the prompt block for the worker.
export function stage(taskId) {
  const list = briefSkills(taskId);
  if (!list.length) return 'Skills: none for this task. Do not load or search for skills.';
  const lines = [];
  for (const { name, why, skill } of list) {
    const dest = path.join(CACHE, name.replace(/[^A-Za-z0-9._-]/g, '_'));
    fs.rmSync(dest, { recursive: true, force: true });
    const budget = { left: MAX_COPY_BYTES, skipped: [] };
    copyDir(path.dirname(skill.file), dest, budget);
    const rel = path.relative(ROOT, path.join(dest, 'SKILL.md')).replace(/\\/g, '/');
    // Free models have ~180k tokens of context; a few large skills can eat half of it before work starts.
    const kb = Math.round(fs.statSync(path.join(dest, 'SKILL.md')).size / 1024);
    const how = kb > SKIM_KB ? `LARGE ${kb} KB: read only its first ${SKIM_LINES} lines, then grep it for what you need` : `${kb} KB: read fully`;
    lines.push(`- ${rel}  (${name}: ${why}) [${how}]${budget.skipped.length ? ` [large files not copied: ${budget.skipped.slice(0, 5).join(', ')}]` : ''}`);
  }
  return ['Skills for this task (read before step 5 as marked; files a skill references sit next to it and are opened only when needed):', ...lines].join('\n');
}

const [cmd, ...args] = process.argv.slice(2);
const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) {
  help("usage: skills.mjs build | find <words> | show <name> | check <TASK> | stage <TASK>");
  try {
    if (cmd === 'build') build();
    else if (cmd === 'find') find(args);
    else if (cmd === 'show') { const s = load().find((x) => x.name === args[0]); if (!s) throw new Error('unknown skill'); console.log(`${s.name}\n${s.file}\n\n${s.description}`); }
    else if (cmd === 'check') { const l = briefSkills(args[0]); console.log(l.length ? l.map((x) => `OK  ${x.name}  ${x.skill.file}`).join('\n') : 'OK  none'); }
    else if (cmd === 'stage') console.log(stage(args[0]));
    else console.log('usage: skills.mjs build | find <words> | show <name> | check <TASK> | stage <TASK>');
  } catch (e) { console.error(e.message); process.exit(2); }
}
